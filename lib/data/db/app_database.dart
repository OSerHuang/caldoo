        await m.addColumn(schema.foods, schema.foods.notes);
      },
      // v4 -> v5: `user_profile` swaps the removed `activity_level` column for
      // a nullable `bmr_kcal_override`. SQLite cannot drop a column on the
      // oldest supported Android versions, so `alterTable` runs the documented
      // 12-step table rebuild: the anthropometrics are copied verbatim, the
      // activity level is dropped and the new nullable column reads as NULL
      // (meaning "derive the BMR with Mifflin-St Jeor").
      from4To5: (Migrator m, Schema5 schema) async {
        await m.alterTable(
          TableMigration(
            schema.userProfile,
            newColumns: <GeneratedColumn>[schema.userProfile.bmrKcalOverride],
          ),
        );
      },
      // v5 -> v6: the stored `age` becomes a date-only `birth_date`. The table
