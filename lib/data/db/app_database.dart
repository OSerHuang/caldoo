///   `notes` until the food is edited.
/// - v8: adds the two optional GB 28050 declarations `sugar_g` and
///   `saturated_fat_g` to `foods` (additive and nullable; blank stays NULL,
///   never 0). The label capture already parsed them, they were simply not
///   stored before.
/// - v9: **data-only** migration retiring the free-text 补充说明 (`notes`). Every
///   row's legacy prose is folded into the structured aliases/servings (an
///   existing structured value wins) and the text is dropped. The column stays
///   for old-backup compatibility but no code writes it any more.
/// - v10: energy becomes integer-only. The four stored energy columns —
///   `foods.kcal`, `meal_items.kcal`, `daily_exercises.kcal` and
///   `user_profile.bmr_kcal_override` — change from REAL to INTEGER; each
///   table is rebuilt (SQLite cannot retype a column in place) and the old
///   fractional values are rounded to the nearest whole kcal.
/// - v11: adds the daily energy goal and the weight history. `user_profile`
///   gains a nullable `daily_kcal_goal_override` INTEGER column (NULL reads as
///   "no goal": the budget stays the resolved BMR), and the new
///   `weight_entries` table (date-only `day_key` PK + `weight_kg`) stores the
///   one-per-day body-weight history. Both are additive, so every existing
///   row survives untouched and the weight history starts empty.
/// - v12: adds the nullable `daily_goal_preset` TEXT column to `user_profile`.
///   It is a **relative** goal re-derived from the current BMR on every read
///   (so it follows the body weight), while the legacy absolute
///   `daily_kcal_goal_override` keeps its fixed custom value. Pure additive
///   nullable column: existing rows survive untouched and read `NULL` (no
///   preset); no value is inferred from the old absolute goal.
