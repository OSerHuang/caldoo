        await m.createTable(schema.dailyExercises);
      },
      // v3 -> v4: the ONLY change is an additive, nullable `notes` column on
      // `foods`; `addColumn` issues
      // `ALTER TABLE foods ADD COLUMN notes TEXT` (NULL default), so every
      // existing food is preserved untouched and the new column reads as null.
