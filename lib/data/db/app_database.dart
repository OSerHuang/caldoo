      // Android versions) and the birthday is back-projected in SQL from the
      // old age as of *migration day*: `date('now','localtime','-N years')`
      // keeps the user's current age, then the date is stored as the UTC
      // epoch seconds drift uses for `dateTime()` columns (so the value is
      // timezone-stable). A Feb-29 birthday can normalise to Mar 1 for
      // non-leap target years — a one-day approximation only.
      from5To6: (Migrator m, Schema6 schema) async {
        await m.alterTable(
          TableMigration(
            schema.userProfile,
            newColumns: <GeneratedColumn>[schema.userProfile.birthDate],
            columnTransformer: <GeneratedColumn, Expression>{
              schema.userProfile.birthDate: const CustomExpression<int>(
                "strftime('%s', date('now', 'localtime', '-' || age || "
                "' years'))",
