    // v1 -> v2 (task 33): the ONLY change is an additive, nullable `notes`
    // column on `meals`. `addColumn` issues
    // `ALTER TABLE meals ADD COLUMN notes TEXT` (NULL default), so existing v1
    // meal rows are preserved untouched and the new column reads as null.
    //
    // v2 -> v3: the session-based `exercises` table is dropped and replaced by
    // the one-per-day `daily_exercises` table. The old rows are intentionally
    // discarded (the feature changed shape; there is no value migration).
    onUpgrade: stepByStep(
      from1To2: (Migrator m, Schema2 schema) async {
        await m.addColumn(schema.meals, schema.meals.notes);
      },
      from2To3: (Migrator m, Schema3 schema) async {
