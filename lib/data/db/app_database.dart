}

/// Root drift database.
///
/// Task 5 stood up the skeleton (schema v1, migration strategy,
/// `app_settings`); task 11 owns the domain tables — `user_profile`, `foods`,
/// `meals`, `meal_items` — plus the one-per-day `daily_exercises` table — and
/// the DAOs in `lib/data/db/daos/`. Rollups are computed on the fly from these
/// tables and are deliberately NOT denormalized into a table, and images are
/// never stored as blobs.
///
/// Schema history (guided migrations, `drift_schemas/app_database/`):
/// - v1: initial schema (task 5 + task 11 tables).
/// - v2: adds a nullable `notes` column to `meals` (task 33).
/// - v3: replaces the session-based `exercises` table with the one-per-day
///   `daily_exercises` table (date-only `day_key` PK + `kcal`). The old
///   exercise rows are deliberately discarded. See the `stepByStep` migration
///   below and the data-integrity test in
///   `test/data/db/app_database/migration_test.dart`.
/// - v4: adds a nullable `notes` column to `foods` (the user's label supplement:
///   package size, aliases, remarks). Additive, so existing foods survive and
///   read `notes` as `NULL`.
/// - v5: replaces the NEAT-only `activity_level` column on `user_profile` with a
///   nullable `bmr_kcal_override` column. The anthropometrics (sex/age/height/
///   weight) are preserved, so an existing profile immediately derives a fresh
///   Mifflin-St Jeor BMR; the old activity level is discarded together with the
///   feature.
/// - v6: replaces the stored `age` column on `user_profile` with a date-only
///   `birth_date` column. The migration back-projects a birthday from the old
///   age so the user's age on migration day is unchanged, and from then on the
///   age is derived (no yearly edit).
/// - v7: gives `foods` its structured selection surface — `aliases`,
///   `servings`, `status` and `basis` (all additive and nullable, so existing
